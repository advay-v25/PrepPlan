/**
 * 2027 bank coverage audit: npx tsx scripts/bank-audit.ts  (writes docs/BANK-COVERAGE-2027.md)
 */
import { writeFileSync } from 'fs'
import * as dotenv from 'dotenv'
dotenv.config({ path: '.env.local', quiet: true } as any)
import { getBankCoverage, MIN_VIABLE_PER_OUTCOME } from '../src/lib/tests/bankCoverage'

async function main() {
  const c = await getBankCoverage()
  const pct = (a: number, b: number) => (b ? `${((a / b) * 100).toFixed(2)}%` : '—')
  const lines: string[] = []
  lines.push('# 2027 question bank coverage', '', `Generated by \`scripts/bank-audit.ts\`. The 20,000 figure is a **target**, apportioned by subject exam-weight midpoint and then by reading pages. It is not a claim that the bank is ready.`, '')
  lines.push(`- Approved items: **${c.total.approved}** of ${c.total.target} (${pct(c.total.approved, c.total.target)})`)
  lines.push(`- By status: ${Object.entries(c.total.byStatus).map(([k, v]) => `${k} ${v}`).join(', ') || 'none'}`)
  lines.push(`- Readings with no approved item: **${c.readingsWithNoItems.length}** of ${c.readings.length}`)
  lines.push(`- Outcomes with no approved item: **${c.outcomesWithNoItems}** of ${c.outcomesTotal}`)
  lines.push(`- Minimum viable coverage (${MIN_VIABLE_PER_OUTCOME} approved items per outcome, every outcome covered): met by **${c.minViableMetReadings}** of ${c.readings.filter(r => !r.structurePending).length} examinable readings`, '')
  lines.push('## By subject', '', '| Subject | Target | Approved | % | Other statuses | Outcomes with no item |', '|---|---:|---:|---:|---|---:|')
  for (const s of c.subjects) lines.push(`| ${s.name} | ${s.target} | ${s.approved} | ${pct(s.approved, s.target)} | ${Object.entries(s.other).map(([k, v]) => `${k} ${v}`).join(', ') || '—'} | ${s.missingOutcomes} |`)
  lines.push('', '## By reading', '', '| Reading | Pages | Outcomes | Target | Approved | Min viable | Met | Outcomes with no item |', '|---|---:|---:|---:|---:|---:|:-:|---:|')
  for (const r of c.readings) lines.push(`| ${r.name}${r.structurePending ? ' (structure pending)' : ''} | ${r.pages} | ${r.outcomes} | ${r.target} | ${r.approved} | ${r.minViable} | ${r.structurePending ? '—' : r.meetsMinViable ? 'yes' : 'no'} | ${r.structurePending ? '—' : r.missingOutcomes} |`)
  writeFileSync('docs/BANK-COVERAGE-2027.md', lines.join('\n') + '\n')
  console.log(lines.slice(0, 9).join('\n'))
  console.log('\nBy subject:'); for (const s of c.subjects) console.log(`  ${s.id.padEnd(6)} target ${String(s.target).padStart(5)}  approved ${String(s.approved).padStart(3)}  outcomes with no item ${s.missingOutcomes}`)
  console.log('\nWritten to docs/BANK-COVERAGE-2027.md')
}
main().catch(e => { console.error(e); process.exit(1) })
