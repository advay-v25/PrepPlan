const assert = require('node:assert/strict')
const path = require('node:path')
const filename = path.resolve('src/lib/study-context.ts')
// Node 24 supports loading TypeScript with erasable type syntax directly.
const { studyContextSchema: schema, contextEnvelopeSchema: envelope, readStudyContext, emptyStudyContext } = require(filename)
assert.equal(schema.safeParse({}).success, true)
assert.equal(schema.safeParse({ examMonth: '2026-11' }).success, false)
assert.equal(schema.safeParse({ examMonth: '2027-13' }).success, false)
assert.equal(schema.safeParse({ examMonth: '2027-02' }).success, true)
assert.equal(schema.safeParse({ timezone: 'Invalid/Zone' }).success, false)
assert.equal(schema.safeParse({ timezone: 'Asia/Kolkata' }).success, true)
assert.equal(schema.safeParse({ sessionMinutes: 500 }).success, false)
assert.equal(schema.safeParse({ availability: ['8-Morning'] }).success, false)
assert.equal(schema.safeParse({ notes: 'x'.repeat(1501) }).success, false)
assert.equal(envelope.safeParse({ version: 4, step: 6, context: {} }).success, false)
assert.equal(schema.parse({ weeklyHours: 100 }).weeklyHours, undefined)
assert.equal(readStudyContext(null).context.sessionMinutes, 0)
assert.equal(readStudyContext({ capacityFactor: 0.1, verdict: 'impossible' }).context.capacityFactor, undefined)
const context = emptyStudyContext(); context.name = 'Sam'
assert.equal(readStudyContext({ version: 4, step: 3, context }).context.name, 'Sam')
console.log('PASS: empty context, exam month bounds, timezone validation, sitting limits, day-part shape, text limits, step bounds, unknown field stripping, safe legacy defaults and v4 round-trip.')
